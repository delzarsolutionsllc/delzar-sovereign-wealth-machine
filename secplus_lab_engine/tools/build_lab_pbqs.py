def _disposal_text(req: dict, today: int) -> str:
    who = "by a disposal vendor" if req["performed_by"] == "third_party" else "in-house"
    text = (f"{req['classification'].capitalize()} {MEDIA[req['media']]} {DEST[req['destination']]}, "
            f"{METHOD[req['method']]} {who}")
    extra = []
    if req["performed_by"] == "third_party":
        extra.append("with a certificate of destruction" if req.get("certificate_of_destruction")
                     else "with no certificate of destruction")
    if req.get("legal_hold"):
        extra.append("while a litigation hold is in place")
    if isinstance(req.get("retention_until"), int) and req["retention_until"] > today:
        extra.append(f"{req['retention_until'] - today} days before its retention period ends")
    return text + (", " + " and ".join(extra) if extra else "")


def lab21(policies: dict) -> list:
    m, data = _mod(21), _data(21)
    cfg, today = policies["asset_mgmt"], data["today"]
    out = []
    # Q: disposal requests -> decision (one per distinct outcome)
    seen, pairs, src, eng = set(), [], [], []
    for req in data["disposals"]:
        d = m.evaluate_disposal(req, cfg, today)
        key = "APPROVE" if d.decision == "APPROVE" else (d.rules[0] if len(d.rules) == 1 else None)
        if key is None or key in seen or key == "unknown_input":
            continue
        seen.add(key)
        pairs.append((_disposal_text(req, today), DISPOSAL_OUTCOME[key]))
        src.append(req["id"])
        eng.append(key)
    pairs, src, eng = pairs[:6], src[:6], eng[:6]
    lv = {c: {d: v.capitalize() for d, v in dd.items()} for c, dd in cfg["min_level"].items()}
    stem = ("Media sanitization levels rank Clear < Purge < Destroy. Minimum levels: internal data "
            f"{lv['internal']['reuse_within_org']} when reused inside the company and {lv['internal']['leaving_org']} "
            f"when it leaves; confidential data {lv['confidential']['leaving_org']}; restricted data leaving the company "
            f"{lv['restricted']['leaving_org']}. Match each disposal request to the decision.")
    out.append(_q("match", "4.2", "Disposal and Decommissioning", 21, stem, _match(pairs),
                  "A disposal is approved only when the method works on that media (degaussing does nothing to flash "
                  "storage), meets the minimum level for the classification and destination, comes with a certificate "
                  "of destruction when a vendor does it, and no legal hold or unexpired retention period applies.",
                  src, eng))

    # Q: inventory reconciliation -> required action
    inv = m.reconcile(data, cfg)
    cmdb = {a["asset_id"]: a for a in data["cmdb"]}
    seen, pairs, src, eng = set(), [], [], []
    for r in inv:
        if len(r.findings) != 1 or r.primary in seen:
            continue
        seen.add(r.primary)
        kind = HOST_KIND[r.hostname]
        a = cmdb.get(r.key)
        if a is None:
            text = f"A {kind} answers today's discovery scan, but its MAC address matches no inventory record"
        else:
            parts = [f"Inventory record for a {kind}, status {a['status']}"]
            parts.append(f"owner {a['owner']}" if a["owner"] else "no owner recorded")
            parts.append(f"classified {a['classification']}" if a["classification"] else "no data classification")
            last = a.get("last_seen")
            parts.append("seen in today's scan" if last == today else f"last seen on the network {_n(today - last, 'day')} ago")
            text = ", ".join(parts)
        pairs.append((text, INVENTORY_OUTCOME[r.primary]))
        src.append(r.key)
        eng.append(r.primary)
    stem = (f"An asset manager reconciles the inventory with a discovery scan. Active assets not seen for more than "
            f"{cfg['missing_after_days']} days count as missing. Match each record to the action it needs.")
    out.append(_q("match", "4.2", "Monitoring and Asset Tracking", 21, stem, _match(pairs),
                  "Enumeration finds devices the inventory does not know (shadow IT); an active asset that has dropped "
                  "off the network may be lost or stolen; every asset needs an accountable owner and a data "
                  "classification, because both drive the controls and the disposal level.", src, eng))
    return out


