#!/usr/bin/env python3
"""
Build performance-based questions (PBQs) from the lab engines.

The hand-written bank (data/exam_bank/pbq.json) asks ordering and matching
tasks in exam language. This tool makes more of them from the labs themselves:
it runs each lab's engine on its sample data (config/default_policies.json +
data/sample_*.json), takes the decisions the engine computes (disposal
approvals, governor verdicts, Conditional Access outcomes, DLP decisions,
evidence volatility, ALE...) and turns them into "match" / "order" / "multi"
records. Only the wording is written here; every answer comes from an engine,
so the questions cannot drift away from what the labs teach. Change the
policies or the sample data and the answers change with them.

Item texts describe the scenario in plain words built from the data (no lab
ids such as "D-4" or rule codes such as "PRIV_GRANT_NO_CAB"); engine verdict
codes are mapped to readable phrases. Output is deterministic (same policies
and data give a byte-identical file).

    python tools/build_lab_pbqs.py            # write data/exam_bank/pbq-labs.json
    python tools/build_lab_pbqs.py --check    # exit 1 if the file is out of date

``build()`` returns ``[(record, truth), ...]``: ``truth`` records the engine
evidence behind each answer (``source`` ids and raw ``engine`` codes, one per
item, in item order) so tests can re-derive answers from the engines.
"""

