# --------------------------------------------------------------------------- #
AGENT_KIND = {"patching": "Patching agent", "firewall": "Firewall agent", "identity": "Identity agent",
              "soc": "SOC triage agent"}
GOVERNOR = {"ALLOW": "Runs automatically", "REQUIRE_HUMAN_APPROVAL": "Held for human approval", "BLOCK": "Blocked"}
GUARDRAIL = {
    "HALLUCINATED_ASSET": "It references something that does not exist in the authoritative records",
    "HALLUCINATED_PATCH": "It references something that does not exist in the authoritative records",
    "HALLUCINATED_TICKET": "It references something that does not exist in the authoritative records",
    "IMMUTABLE_RULE": "It touches a rule that automation may never change",
    "OVERLY_PERMISSIVE_RULE": "It opens an overly permissive path that a human must confirm",
    "PRIV_GRANT_NO_CAB": "It grants a privileged role without an approved change",
    "UNKNOWN_AGENT": "The requester is not a registered non-human identity",
    "OUT_OF_SCOPE_ACTION": "The action is outside the agent's allow-list",
    "DANGEROUS_COMMAND": "The command matches a dangerous pattern",
    "PROMPT_INJECTION": "Its justification contains injected instructions",
    "RATE_LIMIT": "The agent exceeded its action rate limit",
}


def _agent_text(a: dict, pol: dict, crit: set) -> str:
    agent = pol["agents"].get(a["agent_id"])
    who = AGENT_KIND[agent["type"]] if agent else "An agent identity that is not registered"
    p, t, act = a.get("parameters", {}), a.get("target", ""), a["action"]
    tickets = set(pol["approved_cab_tickets"])
    if act == "apply_patch":
        cat = "an approved catalog patch" if p.get("patch") in pol["patch_catalog"] else \
            "a patch ID that is not in the approved patch catalog"
        host = f"host {t}" if t in pol["asset_inventory"] else f"host {t}, which is not in the asset inventory"
        text = f"{who} applies {cat} to {host}"
    elif act == "firewall_rule_modify":
        change = str(p.get("change", "")).replace("->", "to")
        text = (f"{who} edits the firewall's protected default rule ({change})"
                if p.get("rule_id") in pol["immutable_firewall_rules"] else f"{who} edits a firewall rule ({change})")
    elif act == "firewall_rule_add":
        src = "any source" if p.get("src") in ("0.0.0.0/0", "any", "*") else p.get("src")
        port = "any port" if str(p.get("port")) in ("any", "*") else f"port {p.get('port')}"
        text = f"{who} adds a rule allowing {src} to reach {p.get('dst')} on {port} for vendor support"
    elif act == "grant_privilege":
        role = str(p.get("role", "")).replace("_", " ")
        grantee = p.get("user", t)
        whom = "its own agent identity" if grantee == a["agent_id"] or grantee in pol["agents"] else "a user"
        tk = a.get("cab_ticket")
        why = ("citing an approved change ticket" if tk in tickets else
               "citing a change ticket that does not exist" if tk else "with no change ticket")
        text = f"{who} grants the {role} role to {whom}, {why}"
    elif act == "run_command":
        text = f"{who} runs \"{p.get('command')}\" on host {t}"
    elif act == "isolate_host":
        tier = ", a tier-0 directory server" if t in crit else ""
        text = f"{who} isolates host {t}{tier}"
    elif act in ("delete_logs", "clear_logs", "modify_logs"):
        text = f"{who} deletes the audit logs, justifying it with \"{a.get('justification')}\""
    elif act == "modify_control":
        text = f"{who} sets the {str(p.get('control', t)).upper()} control to {p.get('state')}"
    elif act == "open_ticket":
        text = f"{who} opens an incident ticket: {p.get('summary')}"
    elif act == "read_inventory":
        text = f"{who} reads the asset inventory"
    elif act == "restart_service":
        text = f"{who} restarts the {p.get('service')} service on host {t}"
    else:  # pragma: no cover - new action types need wording
        raise KeyError(f"no wording for agent action '{act}'")
    return f"{text} (confidence {a.get('confidence', 1.0):.2f})"


def _govern_one(m, pol: dict, a: dict):
    """Each action is judged on its own (a fresh governor: no rate-limit or quarantine history)."""
    return m.AgentGovernor(pol).evaluate(m.AgentAction.from_dict(a))


def lab5(policies: dict) -> list:
    m, data, pol = _mod(5), _data(5), policies["ai_governance"]
    crit = set(m.CRITICAL_ASSETS)
    acts = {a["id"]: a for a in data["actions"]}
    verdict = {i: _govern_one(m, pol, a) for i, a in acts.items()}
    out = []
    base = (f"An AI governor reviews every action that automation agents propose. Each agent has an allow-list of "
            f"action types; actions on tier-0 assets or with confidence below {pol['confidence_threshold']:.2f} "
            f"need a human, and hard security boundaries are never crossed.")

    # Q: action -> verdict (two of each verdict, in data order)
    chosen, count = [], {k: 0 for k in GOVERNOR}
    for i in ("A01", "A06", "A04", "A09", "A05", "A08"):
        chosen.append(i)
        count[verdict[i].verdict] += 1
    pairs = [(_agent_text(acts[i], pol, crit), GOVERNOR[verdict[i].verdict]) for i in chosen]
    out.append(_q("match", "4.7", "Guard rails and security groups", 5,
                  base + " Match each proposed action to the governor's decision.", _match(pairs),
                  "Guardrails let routine, in-scope work run automatically, escalate high-impact or low-confidence "
                  "actions to a human (ticketing and escalation), and block anything that crosses a hard boundary, "
                  "such as a privileged grant without an approved change or a command piped from the internet "
                  "into a shell.", chosen, [verdict[i].verdict for i in chosen]))

    # Q: action -> the guardrail that stops it (actions whose every violation falls in one guardrail)
    pairs, src, eng, used = [], [], [], set()
    for i, d in verdict.items():
        cats = {GUARDRAIL.get(c) for c in d.codes}
        if len(cats) != 1 or not d.codes or None in cats:
            continue
        cat = cats.pop()
        if cat in used:
            continue
        used.add(cat)
        pairs.append((_agent_text(acts[i], pol, crit), cat))
        src.append(i)
        eng.append(d.codes[0])
    pairs, src, eng = pairs[:6], src[:6], eng[:6]
    extra = [GUARDRAIL["PROMPT_INJECTION"]] if GUARDRAIL["PROMPT_INJECTION"] not in used else []
    out.append(_q("match", "4.7", "Guard rails and security groups", 5,
                  "An automation governor checks each agent action against its guardrails. Match each proposed "
                  "action to the guardrail that stops or escalates it.", _match(pairs, extra),
                  "Agents are non-human identities: they must be registered, may only cite real assets, patches and "
                  "tickets, may never change protected rules such as the default deny, and need an approved change "
                  "for privileged grants. Broad any/any openings go to a human for confirmation.", src, eng))

    # Q: multi — which TWO run automatically?
    pick = ["A12", "A19", "A07", "A10", "A11"]
    allowed = [i for i in pick if verdict[i].verdict == "ALLOW"]
    choices = [_agent_text(acts[i], pol, crit) for i in pick]
    answers = [_agent_text(acts[i], pol, crit) for i in allowed]
    out.append(_q("multi", "4.7", "Guard rails and security groups", 5,
                  base + " Which TWO of these proposed actions would run automatically without human review?",
                  {"choices": choices, "answers": answers, "select": 2},
                  "Opening a ticket and applying a catalog patch to a known host are inside the agents' allow-lists "
                  "and cross no boundary. Self-escalation, deleting audit logs and disabling a protected security "
                  "control are hard boundaries, so automation blocks them outright.",
                  pick, [verdict[i].verdict for i in pick]))
    return out


