BUILDERS = (lab21, lab5, lab8, lab11, lab7, lab25, lab16, lab9, lab18, lab14, lab6, lab10, lab2, lab17, lab13, lab23)


def build(policies: dict | None = None) -> list[tuple[dict, dict]]:
    """``[(record, truth), ...]`` with ids LPBQ-001... in builder order."""
    policies = policies or load_policies()
    out = []
    for b in BUILDERS:
        for rec, truth in b(policies):
            rec["id"] = f"LPBQ-{len(out) + 1:03d}"
            truth["id"] = rec["id"]
            out.append((rec, truth))
    return out


def records(policies: dict | None = None) -> list[dict]:
    return [r for r, _ in build(policies)]


def render(policies: dict | None = None) -> str:
    doc = {"title": TITLE, "note": NOTE, "questions": records(policies)}
    return json.dumps(doc, indent=2, ensure_ascii=False) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if data/exam_bank/pbq-labs.json is out of date")
    args = ap.parse_args(argv)
    text = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(ROOT) if OUT.is_relative_to(ROOT) else OUT} is out of date: run python tools/build_lab_pbqs.py")
            return 1
        print(f"{OUT.relative_to(ROOT) if OUT.is_relative_to(ROOT) else OUT} is up to date ({len(json.loads(text)['questions'])} questions)")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT) if OUT.is_relative_to(ROOT) else OUT} ({len(json.loads(text)['questions'])} questions)")
    return 0


