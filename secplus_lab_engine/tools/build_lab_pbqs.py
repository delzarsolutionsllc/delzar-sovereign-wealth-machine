def _mod(n: int):
    return LABS[n][0]


def _data(n: int) -> dict:
    return load_data(LABS[n][1])


def _money(x: float) -> str:
    return f"${x:,.0f}"


def _n(k, word: str) -> str:
    """'1 hour', '12 hours'."""
    return f"{k:g} {word}" + ("" if k == 1 else "s")


def _lower1(t: str) -> str:
    """Lower-case the first letter unless the first word is an acronym ('WAF + ...')."""
    return t[0].lower() + t[1:] if len(t) > 1 and t[1].islower() else t


def _q(kind: str, objective: str, topic: str, lab: int, stem: str, body: dict, explanation: str,
       source: list, engine: list) -> tuple[dict, dict]:
    rec = {"id": "", "type": kind, "objective": objective, "topic": topic, "lab": lab, "stem": stem, **body,
           "explanation": explanation}
    return rec, {"lab": lab, "source": list(source), "engine": list(engine)}


def _match(pairs: list[tuple[str, str]], extra: list[str] | None = None) -> dict:
    body: dict = {"pairs": [{"item": i, "match": m} for i, m in pairs]}
    if extra:
        body["targets_extra"] = list(extra)
    return body


