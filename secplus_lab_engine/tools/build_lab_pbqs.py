def lab23(policies: dict) -> list:
    m, data, cfg = _mod(23), _data(23), policies["audit"]
    out = []
    pairs, src, eng = [], [], []
    for n, p in zip(data["assessment_needs"], m.plan_all(data, policies)):
        pairs.append((n["description"] + (" (independence required)" if n.get("independence_required") else ""),
                      ASSESSMENT[p.assessment]))
        src.append(n["id"])
        eng.append(p.assessment)
    out.append(_q("match", "5.5", "Attestation and Internal Audits", 23,
                  "Match each situation to the type of audit or assessment that fits it.", _match(pairs[:6]),
                  "A regulator examines what it regulates; the audit committee directs internal audit, but an "
                  "independence requirement needs an outside firm; a SOC 2 report is an auditor's attestation; and a "
                  "team checking its own systems performs a self-assessment.", src[:6], eng[:6]))

    eng_ = data["engagement"]
    pairs, src, ecodes, used = [], [], [], set()
    for a, g in zip(data["actions"], m.gate_all(data, policies)):
        key = "ALLOW" if g.decision == "ALLOW" else (g.rules[0] if len(g.rules) == 1 else None)
        if key is None or key in used or key not in ROE:
            continue
