def _ir_text(desc: str, incident: dict) -> str:
    t = desc
    for h, name in zip(incident["hosts"], ("the infected workstation", "the domain controller")):
        t = t.replace(h, name)
    for acc in incident["accounts"]:
        t = t.replace(f"Disable {acc}", "Disable the compromised account")
    return t


def lab7(policies: dict) -> list:
    m, data = _mod(7), _data(7)
    cat, inc = data["actions"], data["incident"]
    out = []

    # Q: order of volatility — one hashed evidence action per volatility rank
    by_rank: dict[int, str] = {}
    for aid, act in cat.items():
        ev = act.get("evidence")
        if ev and ev.get("hashed") and not act.get("anti_pattern"):
            by_rank.setdefault(ev["volatility_rank"], aid)
    order = [by_rank[k] for k in sorted(by_rank)]
    assert not [i for i in m.grade_playbook("order", order, cat).issues if i.code == "ORDER_OF_VOLATILITY"]
    out.append(_q("order", "4.8", "Digital forensics", 7,
                  "An EDR alert shows malware beaconing from a workstation that is still powered on. Put the evidence "
                  "collection steps in the order they should happen, most volatile evidence first.",
                  {"items": [_ir_text(cat[a]["desc"], inc) for a in order]},
                  "Collect in order of volatility: memory and live network state disappear first, then swap and temp "
                  "files, then the disk, and finally logs held on remote systems, which change least. Hash each item "
                  "as it is acquired to preserve the chain of custody.",
                  order, [cat[a]["evidence"]["volatility_rank"] for a in order]))

    # Q: incident response phases — one step per phase from the model playbook
    expert = data["playbooks"]["expert"]
    first: dict[str, str] = {}
    for aid in expert:
        first.setdefault(cat[aid]["phase"], aid)
    phases = [p for p in m.PHASES if p in first and p != "preparation"][:6]
    steps = [first[p] for p in phases]
    if "scope_analysis" in expert and "analysis" in phases:
        steps[phases.index("analysis")] = "scope_analysis"
    assert not [i for i in m.grade_playbook("phases", steps, cat).issues if i.code == "PHASE_ORDER"]
    out.append(_q("order", "4.8", "Incident response process", 7,
                  "A malware infection has been reported on a workstation. Put the response steps in the order the "
                  "incident response process performs them.",
                  {"items": [_ir_text(cat[a]["desc"], inc) for a in steps]},
                  "After preparation, the process runs detection, analysis, containment, eradication, recovery and "
                  "lessons learned. Containing before eradicating stops the spread, and recovery comes only once the "
                  "threat is removed.", steps, [cat[a]["phase"] for a in steps]))

