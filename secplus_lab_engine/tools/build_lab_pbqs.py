ZONE = {"internet": "the internet", "dmz": "the DMZ", "internal": "the internal network",
        "database": "the database subnet", "management": "the management network", "guest": "guest Wi-Fi"}
FW_PROBLEM = {"ANY_ANY": "Overly permissive any-to-any rule", "SHADOWED": "Shadowed by an earlier rule, so it never matches",
              "REDUNDANT": "Redundant: an earlier rule already allows the same traffic",
              "INSECURE_PROTOCOL": "Permits a protocol that sends credentials in cleartext",
              "OVERLY_BROAD": "Source range is far broader than the hosts that need access"}


def _endpoint(spec: str, zones: dict, role: str) -> str:
    if str(spec).lower() in ("any", "*"):
        return f"any {role}"
    if spec in zones:
        return ZONE.get(spec, spec)
    return spec


def _ports(spec) -> str:
    s = str(spec).lower()
    return "any port" if s in ("any", "*") else ("ports " if "," in s else "port ") + s.replace(",", ", ")


def _rule_text(r: dict, zones: dict) -> str:
    proto = "" if r.get("proto", "any") == "any" else r["proto"].upper() + " "
    return (f"{r['action'].capitalize()} {proto}{_ports(r['ports'])} from {_endpoint(r['src'], zones, 'source')} "
            f"to {_endpoint(r['dst'], zones, 'destination')}")


def lab11(policies: dict) -> list:
    m, data, cfg = _mod(11), _data(11), policies["firewall_audit"]
    rs = data["rulesets"][0]
    zones, rules = rs["zones"], rs["rules"]
    audit = m.audit(rs, cfg)
    targets = set(FW_PROBLEM)
    pairs, src, eng = [], [], []
    for code in FW_PROBLEM:
        for i, r in enumerate(rules):
            if audit.codes_for(r["id"]) & targets != {code}:
                continue
            if code == "INSECURE_PROTOCOL" and not any(f.rule_id == r["id"] and f.code == code and "cleartext" in f.detail
                                                       for f in audit.findings):
                continue
            text = f"Rule {i + 1}: {_rule_text(r, zones)}"
            if code in ("SHADOWED", "REDUNDANT"):
                prev = next(p for j, p in enumerate(rules[:i]) if m.rule_covers(p, r, zones))
                text += f", listed below rule {rules.index(prev) + 1}: {_lower1(_rule_text(prev, zones))}"
            pairs.append((text, FW_PROBLEM[code]))
            src.append(r["id"])
            eng.append(code)
            break
    stem = ("A firewall evaluates its rules top-down and the first match wins. Match each rule from the current edge "
            "firewall to the problem an audit reports for it.")
    return [_q("match", "4.5", "Firewalls", 11, stem, _match(pairs),
               "A rule placed below a broader rule with the opposite action is shadowed and never fires; one below a "
               "broader rule with the same action is redundant. Any-to-any allows defeat the firewall, Telnet sends "
               "credentials in cleartext, and a /8 source spans zones that should be separated.", src, eng)]


